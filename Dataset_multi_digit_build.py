#2 Create a new dataset with images of dimensions 4 images by 4 images (ie 112 * 112 pixels) but that contain several digits, including blanks. 

def create_blank_image():
    # The proper way to create a normalized blank image
    # Value is (0 - 0.1307) / 0.3081 ≈ -0.4242
    normalized_value = -0.1307 / 0.3081
    blank_img = torch.full((1, 28, 28), normalized_value)
    return blank_img


class MultiDigitMNIST(Dataset):
    def __init__(self, source_dataset, num_samples=1000, grid_dim=4):
        """
        Args:
            source_dataset: Original MNIST dataset
            num_samples: Number of multi-digit images to create
            grid_dim: Grid dimension (grid_dim x grid_dim)
            p_blank: Probability of a cell being blank
        """
        self.source_dataset = source_dataset
        self.num_samples = num_samples
        self.grid_dim = grid_dim
        self.p_blank = 0.0
        self.blank_img = create_blank_image()
        self.data = []
        self.labels = []
        
        # Generate the multi-digit images
        self._generate_data()
    
    def _generate_data(self):
        for i in range(self.num_samples):
            # Create a blank canvas for the multi-digit image
            # Shape: [1, grid_dim*28, grid_dim*28]
            multi_img = torch.zeros(1, self.grid_dim*28, self.grid_dim*28)
            # Keep track of which digits are in the image and where
            digits = []
            
            # Fill the grid with digits or blanks
            for row in range(self.grid_dim):
                for col in range(self.grid_dim):
                    # Decide if this cell should be blank
                    if random.random() < self.p_blank:
                        img = self.blank_img
                        digit = -1  # Use -1 to represent blank
                    else:
                        # Pick a random digit from the source dataset
                        idx = random.randint(0, len(self.source_dataset)-1)
                        img, digit = self.source_dataset[idx]
                    
                    # Place the image in the correct position on the canvas
                    r_start = row * 28
                    r_end = (row + 1) * 28
                    c_start = col * 28
                    c_end = (col + 1) * 28
                    
                    multi_img[0, r_start:r_end, c_start:c_end] = img[0]
                    
                    # Record the digit and its position
                    digits.append(digit)
            
            self.data.append(multi_img)
            self.labels.append(digits)
    
    def __len__(self):
        return self.num_samples
    
    def __getitem__(self, idx):
        return self.data[idx], self.labels[idx]
    


def create_multi_digit_dataset(grid_dim=4):
    """
    Create a dataset of multi-digit images.
    
    Args:
        num_samples: Number of multi-digit images to create
        grid_dim: Grid dimension (grid_dim x grid_dim)
        p_blank: Probability of a cell being blank
        
    Returns:
        A MultiDigitMNIST dataset
    """
    train_dataset, test_dataset = Load_MNIST_dataset()
    train_multi_digit_dataset = MultiDigitMNIST(
        train_dataset, 
        num_samples=len(train_dataset),
        grid_dim=grid_dim
    )
    test_multi_digit_dataset = MultiDigitMNIST(
        test_dataset, 
        num_samples=len(test_dataset),
        grid_dim=grid_dim
    )
    print(f'Example of first item in dataset:{train_multi_digit_dataset[0]}')

    torch.save({
        'data': [img.cpu() for img, _ in train_multi_digit_dataset],
        'labels': [label for _, label in train_multi_digit_dataset]
    }, './data/multi_digit_MNIST/train_dataset_multi_digit_MNIST_withoutblanks.pt')
    
    torch.save({
        'data': [img.cpu() for img, _ in test_multi_digit_dataset],
        'labels': [label for _, label in test_multi_digit_dataset]
    }, './data/multi_digit_MNIST/test_dataset_multi_digit_MNIST_withoutblanks.pt')

    return train_multi_digit_dataset, test_multi_digit_dataset



